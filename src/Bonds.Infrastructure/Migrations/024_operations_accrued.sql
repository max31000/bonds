-- Задача 52: НКД операции купли/продажи облигации.
-- accrued_rub - НКД на ВСЮ операцию, РУБЛИ, ВЕЛИЧИНА (>= 0); направление выводится из типа операции
-- (Buy - НКД уплачен продавцу, Sell - получен от покупателя). NULL = брокер не отдал / старая строка.
-- Журнал перечитывается синком целиком (ON DUPLICATE KEY UPDATE), поэтому существующие строки
-- заполнятся на ближайшем синке - отдельного бэкфилла не требуется.
ALTER TABLE operations
    ADD COLUMN accrued_rub DECIMAL(20,6) NULL AFTER quantity;
